// Combines supabase/migrations/*.sql (in order) into one file that sets up an
// empty Supabase project in a single SQL Editor run — used for the test database.
//   npm run db:bundle  →  supabase/.bundle/setup.sql
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const parts = files.map(
  (f) => `-- ===== ${f} =====\n${readFileSync(join(dir, f), "utf8").trim()}\n`,
);
const header = `-- Generated by scripts/bundle-migrations.mjs from ${files.length} migrations.
-- Run once in the SQL Editor of an EMPTY Supabase project. Do not edit by hand.\n\n`;

mkdirSync("supabase/.bundle", { recursive: true });
writeFileSync("supabase/.bundle/setup.sql", header + parts.join("\n"));
console.log(`Wrote supabase/.bundle/setup.sql (${files.length} migrations)`);
